/**
 * RSVP storage in Supabase (table `public.rsvps`), via the REST API so no SDK is needed.
 * Duplicate phone numbers / emails are rejected by unique indexes in the database
 * (see docs/supabase-rsvp.sql); this file turns those errors into friendly messages.
 */

const URL_ = import.meta.env.VITE_SUPABASE_URL?.replace(/\/+$/, '')
const KEY = import.meta.env.VITE_SUPABASE_ANON_KEY
/** which couple this site belongs to (row in `public.customers`) */
export const CUSTOMER_ID = import.meta.env.VITE_SUPABASE_CUSTOMER_ID || 'jyotiwedsabhay'

export const supabaseReady = Boolean(URL_ && KEY)

export interface RsvpInput {
  fullName: string
  /** the table holds exactly one contact per RSVP (check constraint rsvps_contact_present) */
  contactType: 'phone' | 'email'
  contact: string
  partySize: number
  events: string[]
  message: string
  audience?: string
}

/** A problem the guest can fix (shown next to a field), or a general failure. */
export class RsvpError extends Error {
  constructor(
    message: string,
    public field?: 'phone' | 'email',
  ) {
    super(message)
  }
}

/** Digits only; Indian numbers lose their +91 / 0 prefix so 98694 83112 and +91-98694-83112 match. */
export function normalisePhone(raw: string) {
  let d = raw.replace(/\D/g, '')
  if (d.length === 12 && d.startsWith('91')) d = d.slice(2)
  else if (d.length === 11 && d.startsWith('0')) d = d.slice(1)
  return d
}
export const normaliseEmail = (raw: string) => raw.trim().toLowerCase()

const uuid = () =>
  crypto.randomUUID?.() ??
  'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16)
  })

export async function submitRsvp(input: RsvpInput) {
  if (!URL_ || !KEY) throw new Error('Supabase is not configured')
  const phone = input.contactType === 'phone' ? input.contact.trim() : ''
  const email = input.contactType === 'email' ? input.contact.trim() : ''
  const row: Record<string, unknown> = {
    submission_id: uuid(),
    customer_id: CUSTOMER_ID,
    audience: input.audience || 'all',
    full_name: input.fullName.trim(),
    contact_type: input.contactType,
    // stored cleaned up, so +91 98694-83112 and 9869483112 hit the same unique index
    // (phone_normalized / email_normalized are generated by the database from these)
    phone: phone ? normalisePhone(phone) : null,
    email: email ? normaliseEmail(email) : null,
    attending: true,
    events: input.events,
    party_size: input.partySize,
    message: input.message.trim() || null,
  }

  const send = (body: Record<string, unknown>) =>
    fetch(`${URL_}/rest/v1/rsvps`, {
      method: 'POST',
      headers: {
        apikey: KEY,
        Authorization: `Bearer ${KEY}`,
        'Content-Type': 'application/json',
        Prefer: 'return=minimal',
      },
      body: JSON.stringify(body),
    })

  const res = await send(row)
  const err = res.ok ? null : await res.json().catch(() => ({}))
  if (!err) return

  // unique violation: this phone / email has already RSVP'd
  if (err.code === '23505') {
    if (input.contactType === 'email') throw new RsvpError('This email has already been used to RSVP.', 'email')
    throw new RsvpError('This phone number has already been used to RSVP.', 'phone')
  }
  throw new Error(err.message || `HTTP ${res.status}`)
}
